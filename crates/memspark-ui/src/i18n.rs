pub fn detect_ui_language() -> UiLanguage {
    match std::env::var("MEMSPARK_UI_LANG") {
        Ok(value) if value.eq_ignore_ascii_case("en") || value.eq_ignore_ascii_case("en-US") => {
            UiLanguage::EnUs
        }
        _ => UiLanguage::ZhCn,
    }
}

pub fn texts_for_language(language: UiLanguage) -> &'static UiTexts {
    match language {
        UiLanguage::ZhCn => &ZH_CN,
        UiLanguage::EnUs => &EN_US,
    }
}

